/**
 * A local index of real book subjects, so the dropdown can answer the first
 * keystroke.
 *
 * **Not a taxonomy we invented.** Every line is Open Library's own heading with
 * Open Library's own work count, harvested once from
 * `/search/subjects.json` and shipped. That distinction is the whole reason
 * this file is allowed to exist: the categories screen refuses to make up a
 * category list — BISAC is licensed and a list of our own would be exactly the
 * invented vocabulary the tool was built to avoid — but caching the
 * catalogue's answers is not inventing them. Open Library's data is CC0.
 *
 * **It exists because the live index cannot answer one letter.** `m*` is an
 * HTTP 500 on their side, and plain `m` matches middle initials, returning
 * "Nixon, richard m." and "Kennedy, john f.". Every autocomplete worth using
 * suggests from the first character, so the first character is answered here
 * and the network is asked from the second — which is also what makes the
 * dropdown feel instant, since the common cases never wait for a request.
 *
 * **How it was made**, so it can be made again. About ninety broad seed terms
 * — the genres and shelves this app already knows, plus the main non-fiction
 * ones — were each searched against `/search/subjects.json`; every result of
 * `subject_type: "subject"` with 40 or more works was collected and
 * de-duplicated; anything that fails the cleaning in `subjects.ts` (the
 * administrative and too-broad rules) was dropped; the remainder was sorted by
 * work count and cut to the first 900. It cost about ninety requests, once.
 *
 * **It goes stale slowly and harmlessly.** Subject headings are not fashion,
 * and anything missing is still found the moment a second character is typed,
 * because the live index is queried in parallel and the two are merged.
 * Nothing breaks if this file is never touched again.
 *
 * Written as tuples rather than objects: 900 `{ name, works }` literals cost
 * roughly a third more bytes to say the same thing on a page a writer is
 * waiting for.
 */
