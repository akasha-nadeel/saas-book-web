/**
 * Every British and American spelling pair this book is checked against.
 *
 * **Generated — do not hand-edit.** `scripts/build-spelling-pairs.cjs` builds it
 * from VarCon, and the reasoning for the *shape* of this data lives beside its
 * one caller in `consistency.ts`: a table, and not a rule that derives one.
 *
 * ## Where it comes from
 *
 * [VarCon](https://wordlist.aspell.net/varcon-readme/) (Variant Conversion
 * Info), by Kevin Atkinson and Benjamin Titze, verified against Oxford
 * dictionaries. Its licence grants permission to "use, copy, modify, distribute
 * and sell" without fee, so it is safe in a paid product; the copyright notice
 * travels in the build script. VarCon is **no longer maintained** — it has been
 * folded into the English Speller Database, whose format is harder to read — so
 * this is a snapshot rather than a living source.
 *
 * ## What was thrown away, and why
 *
 * This was 112 pairs typed by hand, which meant the check found `colour/color`
 * and was blind to `sulphur/sulfur`. Going to a few thousand is only safe
 * because the filtering is aggressive — **the failure this check cannot afford
 * is a false positive**, and a pair where one side is an ordinary word with
 * another meaning fires on nearly every novel:
 *
 * - **Rows carrying a sense note are dropped.** VarCon marks a pair whose two
 *   words mean different things — `story / storey | level of building`,
 *   `check / cheque | bank`, `tire / tyre | wheel`, `draft / draught | current
 *   of air`, `curb / kerb | street edge`. That one rule caught every trap the
 *   hand-written list had found the hard way, and 733 rows went with it.
 * - **Only common words.** SCOWL level 60 and below — a novel does not contain
 *   `antagonizable`.
 * - **The American form has to be a real word**, checked against a plain word
 *   list at build time. VarCon carries machine-made inflections for
 *   spellcheckers — `colorrest`, `lacklusterrer`, `unauthorizedder` — that no
 *   one writes. **Only the American side is tested**: the word list is
 *   US-biased and is missing `favourites`, `organisations`, `recognises` and
 *   800 more real British forms, so testing both sides threw away good pairs.
 * - **Possessives and words under four letters** never survive; the tokeniser
 *   strips `'s` before it gets here anyway.
 *
 * ## What it costs
 *
 * **23.7 KB gzipped**, measured, and it is downloaded once and cached. The cap
 * was raised from SCOWL level 60 to 70 knowing most of the new entries are
 * words no novel contains — because a spelling table that stops early is the
 * one failure a writer notices as *the tool missed it*, and that is worth more
 * than ten kilobytes. Two sibling tables ship beside it, `style-pairs.ts` and
 * `name-words.ts`, for 31.3 KB in total.
 *
 * Nothing is filtered for ambiguity *here*. `AMBIGUOUS_PAIRS` in
 * `consistency.ts` is the one statement of that judgement, applied at the point
 * of use, so a pair added by hand is refused by the same rule as a generated
 * one.
 *
 * ## Two of these are riskier than the rest
 *
 * `metre / meter` and `spelt / spelled` were in the hand-written list and are
 * kept. VarCon disagrees with both — a meter is a thing that measures and spelt
 * is a species of wheat — so if a false positive is ever reported on this
 * check, start there.
 */
